class GroqKeyManager:
    def __init__(self, max_keys=4):
        self.max_keys = max_keys
        self.keys = []
        self.current_idx = 0

        # Check Colab Secrets for GROQ_API_KEY, GROQ_API_KEY_2, GROQ_API_KEY_3
        try:
            from google.colab import userdata
            for suffix in ["", "_2", "_3","_4"]:
                k = userdata.get(f"GROQ_API_KEY{suffix}")
                if k and k.strip() and k.strip() not in self.keys:
                    self.keys.append(k.strip())
        except Exception:
            pass

        # Check environment variables
        for suffix in ["", "_2", "_3","_4"]:
            k = os.environ.get(f"GROQ_API_KEY{suffix}")
            if k and k.strip() and k.strip() not in self.keys:
                self.keys.append(k.strip())

        if not self.keys:
            primary_key = getpass("Enter Groq API key: ").strip()
            if primary_key:
                self.keys.append(primary_key)

        self.client = None
        self._set_client()

    def _set_client(self):
        if self.keys:
            self.client = OpenAI(
                api_key=self.keys[self.current_idx],
                base_url="https://api.groq.com/openai/v1"
            )

    def handle_rate_limit(self):
        if self.current_idx + 1 < len(self.keys):
            self.current_idx += 1
            print(f"\n[KeyManager] 429 rate limit hit. Switching to key #{self.current_idx + 1}...")
            self._set_client()
            return True

        if len(self.keys) < self.max_keys:
            prompt_msg = f"\n[KeyManager] Rate limit hit on key #{self.current_idx + 1}. Enter Groq API key #{len(self.keys) + 1} of {self.max_keys}: "
            new_key = getpass(prompt_msg).strip()
            if new_key and new_key not in self.keys:
                self.keys.append(new_key)
                self.current_idx = len(self.keys) - 1
                self._set_client()
                print(f"[KeyManager] Key #{self.current_idx + 1} added! Resuming...")
                return True

        print("\n[KeyManager] All loaded keys hit rate limit. Waiting 15s for quota window to reset...")
        time.sleep(15)
        self.current_idx = 0
        self._set_client()
        return True

